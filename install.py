#!/usr/bin/env python3
"""Install a skill folder (SKILL.md + references/ + scripts/) into a project for AI coding tools.

The skill is plain markdown and Python, so it is the same for every tool. This
installer copies it into the target project and writes the small "pointer" file
each tool uses to discover instructions. The skill name and description are read
from SKILL.md, so the same installer works for any skill laid out this way.

  python3 install.py --target /path/to/your-repo --tool cursor
  python3 install.py --target . --tool all

Tools:
  claude    .claude/skills/<name>/                     (Claude Code skill)
  cursor    .cursor/rules/<name>.mdc                   (+ .<name>/)
  copilot   .github/prompts/<name>.prompt.md           (+ .<name>/)
  windsurf  .windsurf/rules/<name>.md                  (+ .<name>/)
  cline     .clinerules/<name>.md                      (+ .<name>/)
  agents    AGENTS.md section (Codex, Gemini CLI, Copilot agent, others)
  all       everything above

Re-running is safe: files this script generated are refreshed; files it did not
generate are left alone unless you pass --force. Python 3.8+, stdlib only.
"""
import argparse
import json
import os
import re
import shutil
import sys

SKILL_ITEMS = ["SKILL.md", "references", "scripts"]
TOOLS = ["claude", "cursor", "copilot", "windsurf", "cline", "agents"]


def read_frontmatter(skill_md):
    with open(skill_md, encoding="utf-8") as f:
        text = f.read()
    name = re.search(r"^name:\s*(.+)$", text, re.M)
    desc = re.search(r"^description:\s*(.+)$", text, re.M)
    if not name or not desc:
        sys.exit("error: SKILL.md frontmatter must contain name and description")
    return name.group(1).strip(), desc.group(1).strip()


def copy_skill(src, dest):
    os.makedirs(dest, exist_ok=True)
    for item in SKILL_ITEMS:
        s = os.path.join(src, item)
        d = os.path.join(dest, item)
        if not os.path.exists(s):
            continue
        if os.path.isdir(s):
            shutil.copytree(s, d, dirs_exist_ok=True,
                            ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        else:
            shutil.copy2(s, d)
    print(f"  copied skill -> {dest}")


class Installer:
    def __init__(self, src, target, name, desc, force):
        self.src, self.target, self.name, self.desc, self.force = src, target, name, desc, force
        self.neutral = f".{name}"
        self.marker = f"generated by {name} install.py"
        self.a_start = f"<!-- {name}:start -->"
        self.a_end = f"<!-- {name}:end -->"

    def body(self):
        path = f"{self.neutral}/SKILL.md"
        return (
            f"<!-- {self.marker} -->\n"
            f"# {self.name}\n\n"
            f"When the user's request matches this skill's description, follow the full instructions in "
            f"`{path}` exactly. Read that file first, then read the files it points to under "
            f"`{self.neutral}/references/` when a phase says to, and run the scripts under "
            f"`{self.neutral}/scripts/` as it instructs.\n\n"
            "Run in agent mode (the agent must be able to read the repo, write files and run shell commands).\n"
        )

    def write_generated(self, rel, content):
        path = os.path.join(self.target, rel)
        if os.path.exists(path) and not self.force:
            with open(path, encoding="utf-8") as f:
                if self.marker not in f.read():
                    print(f"  skipped {path} (exists and was not generated by this installer; use --force)")
                    return
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"  wrote {path}")

    def claude(self):
        copy_skill(self.src, os.path.join(self.target, ".claude", "skills", self.name))

    def cursor(self):
        fm = f"---\ndescription: {json.dumps(self.desc)}\nglobs:\nalwaysApply: false\n---\n"
        self.write_generated(os.path.join(".cursor", "rules", f"{self.name}.mdc"), fm + self.body())

    def copilot(self):
        fm = f"---\nagent: agent\ndescription: {json.dumps(self.desc)}\n---\n"
        self.write_generated(os.path.join(".github", "prompts", f"{self.name}.prompt.md"), fm + self.body())

    def windsurf(self):
        fm = f"---\ntrigger: model_decision\ndescription: {json.dumps(self.desc)}\n---\n"
        self.write_generated(os.path.join(".windsurf", "rules", f"{self.name}.md"), fm + self.body())

    def cline(self):
        self.write_generated(os.path.join(".clinerules", f"{self.name}.md"), self.body())

    def agents(self):
        path = os.path.join(self.target, "AGENTS.md")
        section = f"{self.a_start}\n{self.body()}{self.a_end}\n"
        existing = ""
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                existing = f.read()
        if self.a_start in existing and self.a_end in existing:
            pat = re.compile(re.escape(self.a_start) + r".*?" + re.escape(self.a_end) + r"\n?", re.S)
            new = pat.sub(lambda _: section, existing)
        else:
            new = (existing.rstrip() + "\n\n" if existing.strip() else "") + section
        with open(path, "w", encoding="utf-8") as f:
            f.write(new)
        print(f"  updated {path} (section between {self.name} markers)")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--target", default=".", help="project to install into (default: current directory)")
    ap.add_argument("--tool", action="append", choices=TOOLS + ["all"],
                    help="tool to set up; repeat for several, or use 'all'")
    ap.add_argument("--force", action="store_true", help="overwrite adapter files not generated by this installer")
    args = ap.parse_args()

    tools = args.tool or []
    if not tools:
        sys.exit("error: choose at least one --tool (claude, cursor, copilot, windsurf, cline, agents, all)")
    if "all" in tools:
        tools = TOOLS

    src = os.path.dirname(os.path.abspath(__file__))
    target = os.path.abspath(args.target)
    if not os.path.isdir(target):
        sys.exit(f"error: target {target} is not a directory")
    if os.path.samefile(src, target):
        sys.exit("error: target is the skill folder itself; point --target at your project repo")
    name, desc = read_frontmatter(os.path.join(src, "SKILL.md"))

    inst = Installer(src, target, name, desc, args.force)
    print(f"Installing {name} into {target}")
    if any(t != "claude" for t in tools):
        copy_skill(src, os.path.join(target, inst.neutral))
    for t in tools:
        print(f"[{t}]")
        getattr(inst, t)()

    print("\nDone. Open your AI tool in agent mode and ask it to run the skill (see README).")


if __name__ == "__main__":
    main()
